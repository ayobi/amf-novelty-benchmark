"""Outcomes of the LongGloDB test against the protocol and the lock (PROTOCOL_LGDB.md section 5,
amendments 1 and 2). Reads runs_lgdb/06_scores; writes runs_lgdb/report/. Nothing is fitted here.

Primary outcome: false-known calls among novel-species and novel-lineage ASVs under condition B
(protocol v2 scoring, i.e. with N6), by ASV and averaged over species and over cultures.
Test of the complex claim: every false known is checked against the locked 'inside' set (primary
test) and against the set under the paper's percentile definition (amendment 1).
"""
from collections import Counter, defaultdict
import json
from pathlib import Path
import statistics

from lsu_placement import read_tsv, write_tsv
import lgdb_test as L


def is_known(r):
    return r['status'].startswith('known')


def macro(rows, key):
    by = defaultdict(list)
    for r in rows:
        by[r[key]].append(is_known(r))
    return statistics.mean(statistics.mean(v) for v in by.values()) if by else None


def pct(a, b):
    return f'{100 * a / b:.1f}%' if b else '-'


def false_known_block(rows):
    novel = [r for r in rows if r['test_role'] in L.NOVEL_ROLES]
    fk = [r for r in novel if is_known(r)]
    out = {'asvs': len(novel), 'false_known': len(fk), 'species_macro': macro(novel, 'organism'), 'culture_macro': macro(novel, 'culture')}
    for role in L.NOVEL_ROLES:
        sub = [r for r in novel if r['test_role'] == role]
        out[role] = {'asvs': len(sub), 'false_known': sum(map(is_known, sub))}
    return out


def report(inputs, out):
    scores = out / '06_scores'
    if not (scores / 'stage.json').exists():
        raise SystemExit(f'no completed scores in {scores}; run first')
    rep = out / 'report'; rep.mkdir(exist_ok=True)
    t = {p.name.replace('.copies.tsv', ''): read_tsv(p) for p in sorted(scores.glob('*.copies.tsv'))}
    meta = json.loads((scores / 'scores.json').read_text())
    pred = inputs.pred
    locked = {x for x, r in pred.items() if r['role'] in L.NOVEL_ROLES and r['inside']}
    frozen_def = locked | set(L.FROZEN_DEFINITION_EXTRA)
    asv_meta = {r['asv']: r for r in inputs.asvs}
    cul_meta = inputs.cultures
    lines, summary = [], {'scores': meta}

    def h(text):
        lines.append(f'\n## {text}\n')

    lines.append('# LongGloDB independent-culture test: results\n')
    lines.append('Protocol `PROTOCOL_LGDB.md` with amendments 1 and 2; frozen M2b code and protocol v2 (N6). '
                 'Generated by `lgdb_report.py`; every number below comes from the score tables in `06_scores`.')

    # 1. integrity
    h('1. Integrity checks')
    ev = json.loads((out / '01_evidence/evidence_report.json').read_text())
    pa = json.loads((out / 'A/parity.json').read_text())
    par = meta['parity_m4']
    lines.append(f"- M4 parity: all {par['copies']} copies of the {par['folds']} M4 species folds rescored with the test cultures present and excluded; "
                 'every status, placement, reason and N6 decision equals the stored M4 v2 result.')
    lines.append(f"- Evidence: the frozen VT and SH evidence was reproduced exactly for all {ev['VT']['reference_copies_reproduced']} reference copies.")
    lines.append(f"- VT arm on the test ASVs: {ev['VT']['test_with_anchor']} of {ev['VT']['test_queries']} have a hit passing the frozen coverage, "
                 f"{ev['VT_spanned']['test_with_anchor']} with coverage over the spanned part (secondary); the secondary rule would change the evidence of "
                 f"{ev['VT_spanned']['reference_copies_whose_evidence_would_change']} reference copies.")
    lines.append(f"- SH arm: {ev['SH']['test_with_anchor']} of {ev['SH']['test_queries']} test ASVs have a passing UNITE hit.")
    lines.append(f"- Condition A diagnostic: re-aligning the 903 reference windows together with the test windows left "
                 f"{pa['alignment_identical']} alignments and {pa['credible_species_clade_units_identical']} credible unit sets identical "
                 '(scores use the frozen placements for the reference copies).')
    lines.append(f"- N6 threshold (all v4 cultures train): {meta['its_threshold_pct']:.3f}% from {meta['its_threshold_n']} distances.")
    summary['integrity'] = {'evidence': ev, 'A_parity': pa}

    # 2. primary outcome
    h('2. Primary outcome: false-known calls among novel test ASVs')
    rows_out = []
    lines.append('| Condition | Analysis | N6 | ASVs | False known | Share | Species-averaged | Culture-averaged |')
    lines.append('|---|---|---|---|---|---|---|---|')
    for cond in ('B', 'A'):
        for analysis in ('primary', 'secondary_vt'):
            for ver in ('v2', 'v1'):
                name = f'{cond}_{analysis}_{ver}'
                if name not in t:
                    continue
                b = false_known_block(t[name])
                summary[name] = b
                lines.append(f"| {cond} | {analysis.replace('_', ' ')} | {'yes' if ver == 'v2' else 'no'} | {b['asvs']} | {b['false_known']} | "
                             f"{pct(b['false_known'], b['asvs'])} | {100 * b['species_macro']:.1f}% | {100 * b['culture_macro']:.1f}% |")
    p = summary['B_primary_v2']
    lines.append(f"\nPrimary outcome (B, primary analysis, with N6): **{p['false_known']} of {p['asvs']} ASVs ({pct(p['false_known'], p['asvs'])})**; "
                 f"novel species {p['novel species, genus in v4']['false_known']} of {p['novel species, genus in v4']['asvs']}, "
                 f"novel lineage {p['novel lineage, genus not in v4']['false_known']} of {p['novel lineage, genus not in v4']['asvs']}.")

    # 3. complex claim
    h('3. Test of the complex claim against the lock')
    contradictions = {}
    for name in ('B_primary_v2', 'A_primary_v2', 'B_primary_v1', 'A_primary_v1', 'B_secondary_vt_v2', 'A_secondary_vt_v2'):
        if name not in t:
            continue
        for r in t[name]:
            if r['test_role'] in L.NOVEL_ROLES and is_known(r):
                rows_out.append({'table': name, 'fold': r['fold'], 'accession': r['accession'], 'culture': r['culture'], 'role': r['test_role'],
                                 'called': r['placement'], 'status': r['status'], 'locked_inside': pred[r['accession']]['inside'],
                                 'in_locked_set': int(r['accession'] in locked), 'in_frozen_definition_set': int(r['accession'] in frozen_def),
                                 'reasons': r['reasons']})
        fk = [x for x in rows_out if x['table'] == name]
        contradictions[name] = {'false_known': len(fk), 'outside_locked_set': sum(not x['in_locked_set'] for x in fk),
                                'outside_frozen_definition_set': sum(not x['in_frozen_definition_set'] for x in fk)}
    write_tsv(rep / 'false_known.tsv', rows_out)
    summary['complex_claim'] = contradictions
    lines.append(f"Locked set: {len(locked)} novel ASVs predicted inside a v4 species ({', '.join(sorted({pred[x]['organism'] + ' ' + pred[x]['code'] for x in locked}))}); "
                 f"frozen-definition set adds {', '.join(L.FROZEN_DEFINITION_EXTRA)} (amendment 1).\n")
    lines.append('| Table | False known | Outside the locked set (primary test) | Outside the frozen-definition set |')
    lines.append('|---|---|---|---|')
    for name, c in contradictions.items():
        lines.append(f"| {name} | {c['false_known']} | {c['outside_locked_set']} | {c['outside_frozen_definition_set']} |")
    c = contradictions.get('B_primary_v2', {})
    verdict = ('The claim is not contradicted: no novel ASV outside the locked set was called a known species.'
               if c.get('outside_locked_set') == 0 else
               f"The claim is contradicted: {c.get('outside_locked_set')} novel ASV(s) outside the locked set were called a known species (see false_known.tsv).")
    lines.append(f'\n{verdict}')

    # 4. known-species retention under A
    h('4. Known-species retention under condition A')
    a = [r for r in t['A_primary_v2'] if r['test_role'] == 'known species']

    def outcome(r):
        if is_known(r):
            return 'kept (own species in the call)' if r['organism'] in r['placement'].split(';') else 'known, other species'
        return r['status']
    def identical(x):
        m = asv_meta[x]
        return m['nearest_its_pct'] not in ('', None) and float(m['nearest_its_pct']) == 0.0 and m['nearest_v4'].split(' | ')[0] == m['organism']
    split = defaultdict(Counter)
    for r in a:
        split['ITS identical to a Stefani copy' if identical(r['accession']) else 'not identical'][outcome(r)] += 1
        split['all'][outcome(r)] += 1
    keys = sorted({k for s in split.values() for k in s})
    lines.append('| Subset | ASVs | ' + ' | '.join(keys) + ' |')
    lines.append('|---|---|' + '---|' * len(keys))
    for sub in ('all', 'ITS identical to a Stefani copy', 'not identical'):
        s = split.get(sub, Counter())
        lines.append(f"| {sub} | {sum(s.values())} | " + ' | '.join(str(s.get(k, 0)) for k in keys) + ' |')
    per_c = []
    for cul in sorted({r['culture'] for r in a}):
        rs = [r for r in a if r['culture'] == cul]
        oc = Counter(outcome(r) for r in rs)
        pi = Counter(('inside own' if pred[r['accession']]['own_species_in_v4'] in pred[r['accession']]['inside'].split('; ')
                      else 'inside ' + pred[r['accession']]['inside'] if pred[r['accession']]['inside'] else 'inside none') for r in rs)
        per_c.append({'culture': cul, 'asvs': len(rs), 'outcomes': '; '.join(f'{k} {v}' for k, v in oc.most_common()),
                      'locked_prediction': '; '.join(f'{k} {v}' for k, v in pi.most_common())})
    write_tsv(rep / 'known_retention_by_culture.tsv', per_c)
    summary['known_retention_A'] = {k: dict(v) for k, v in split.items()}

    # 5. genus calls and rank against the expected rank
    h('5. Genus calls and novelty rank (novel ASVs)')
    expected = {'novel species, genus in v4': 'novel species, genus known', 'novel lineage, genus not in v4': 'novel lineage'}
    lines.append('| Condition | Role | ASVs | Expected rank | Status counts | Genus right | Genus wrong | No genus |')
    lines.append('|---|---|---|---|---|---|---|---|')
    for cond in ('B', 'A'):
        rows = t[f'{cond}_primary_v2']
        for role in L.NOVEL_ROLES:
            rs = [r for r in rows if r['test_role'] == role]
            st = Counter(r['status'] for r in rs)
            right = sum(r['final_genus_call'] == '1' and r['final_genus_compatible'] == '1' for r in rs)
            wrong = sum(r['final_genus_call'] == '1' and r['final_genus_compatible'] != '1' for r in rs)
            none = sum(r['final_genus_call'] != '1' for r in rs)
            lines.append(f"| {cond} | {role} | {len(rs)} | {expected[role]} ({st.get(expected[role], 0)}) | "
                         + '; '.join(f'{k} {v}' for k, v in st.most_common()) + f' | {right} | {wrong} | {none} |')
            summary[f'genus_{cond}_{role}'] = {'status': dict(st), 'genus_right': right, 'genus_wrong': wrong, 'no_genus': none}

    # 6. D1 among the test ASVs
    h('6. Short-5.8S (D1) calls among the test ASVs, condition A')
    d1 = [r for r in t['A_primary_v2'] if r.get('d1_short') == '1']
    short = [x for x, s in inputs.win['s58'].items() if len(s) <= 153]
    lines.append(f"D1 fired for {len(d1)} test ASVs; {len(short)} test ASVs have a 5.8S of 153 bp or less.")
    for r in d1:
        lines.append(f"- {r['accession']} ({r['test_role']}): {r['s58']}")
    for x in sorted(set(short) - {r['accession'] for r in d1}):
        r = next(r for r in t['A_primary_v2'] if r['accession'] == x)
        lines.append(f"- not called: {x} ({len(inputs.win['s58'][x])} bp; status {r['status']}; {r['s58'] or 'no comparators'})")
    summary['d1'] = {'fired': len(d1), 'short_58s_asvs': len(short)}

    # 7. cultures whose LSU matches V18 at >= 99.5%
    h('7. Cultures whose LSU matches a V18 record at 99.5% or more (condition A, reported apart)')
    near = {k for k, v in cul_meta.items() if v.get('v18_best_pct') and float(v['v18_best_pct']) >= 99.5}
    novel_a = [r for r in t['A_primary_v2'] if r['test_role'] in L.NOVEL_ROLES]
    tag = lambda r: (r['organism'], r['test_code']) in near
    for label, sub in (('V18 >= 99.5%', [r for r in novel_a if tag(r)]), ('others', [r for r in novel_a if not tag(r)])):
        lines.append(f"- {label}: {len(sub)} novel ASVs, false known {sum(map(is_known, sub))}")

    # 8. VT state, boundary and flags
    h('8. VT arm state, boundary calls and flags')
    for name in ('A_primary_v2', 'A_secondary_vt_v2'):
        rows = t.get(name, [])
        vt = Counter(r['VT_state'] for r in rows)
        lines.append(f"- {name}: VT {dict(vt)}; boundary (B1) {sum(r['status'] == 'boundary' for r in rows)}; "
                     f"B2 flags {sum('B2' in r['flags'] for r in rows)}; Q1 flags {sum('Q1' in r['flags'] for r in rows)}")
    if 'A_secondary_vt_v2' in t:
        prim = {r['accession']: r for r in t['A_primary_v2']}
        ch = [r for r in t['A_secondary_vt_v2'] if r['status'] != prim[r['accession']]['status']]
        vtch = sum(r['VT_state'] != prim[r['accession']]['VT_state'] for r in t['A_secondary_vt_v2'])
        lines.append(f"- secondary against primary (A): VT state changed for {vtch} ASVs, status for {len(ch)}")
        write_tsv(rep / 'secondary_status_changes_A.tsv', [{'accession': r['accession'], 'role': r['test_role'], 'primary': prim[r['accession']]['status'],
                                                           'secondary': r['status'], 'primary_call': prim[r['accession']]['placement'],
                                                           'secondary_call': r['placement']} for r in ch])

    (rep / 'report.md').write_text('\n'.join(lines) + '\n')
    (rep / 'report.json').write_text(json.dumps(summary, indent=2, sort_keys=True, default=str) + '\n')
    print('\n'.join(lines))
    print(f'\nwritten: {rep}/report.md, report.json, false_known.tsv, known_retention_by_culture.tsv')
