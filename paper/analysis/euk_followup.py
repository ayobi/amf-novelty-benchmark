#!/usr/bin/env python3
"""Exploratory follow-up of the EUKARYOME test, written AFTER its results were seen (numbers_euk_followup.tex).

The locked test (PROTOCOL_EUK.md) and its numbers (euk_numbers.py) are not changed. This script only describes
why the false-known assignments outside the locked prediction arose, and adds a few derived shares:

  * the share of false-known assignments among sequences of absent species in reference genera, and how many
    absent species contributed them;
  * for each false-known sequence of the primary outcome (condition B where planned, with the ITS rule): its
    distance on each marker (full ITS, LR0R-FLR2, SSU region) to the main-type sequences of EVERY reference
    culture, named or identified only to genus. The locked prediction, like the complex rule, measures distance
    to named species only; a sequence that lies inside a genus-only culture on all three markers is outside the
    prediction by construction;
  * what the ITS distance rule prevented and cost in this test;
  * how often sequences of absent genera were given a genus, with the LSU reference with and without them.

Distances as in stage3/predict_longglodb.py: edlib infix edit distance as % of the shorter sequence. The test
windows are the locked overlap.win.*.fasta files (EUKARYOME sequences; not stored in git).

  python3 analysis/euk_followup.py --runs PATH/runs_euk --wins PATH/overlap.win --paper .
"""
import argparse
from collections import Counter, defaultdict
import os
from pathlib import Path
import sys

import edlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from euk_numbers import NOVEL, NOVEL_SP, NOVEL_LIN, KNOWN, NO_GENUS_OUTCOME_GENERA, Macros, called, is_known, num, pct, rd  # noqa: E402

MARKERS = [('full_its', 'ITS'), ('LSU_LROR-FLR2', 'LSU'), ('ssu_flank', 'SSU')]


def read_fasta(path):
    seqs, name = {}, None
    for line in open(path):
        line = line.strip()
        if line.startswith('>'):
            name = line[1:].split()[0]
            seqs[name] = []
        elif name:
            seqs[name].append(line.upper())
    return {k: ''.join(v) for k, v in seqs.items()}


def dist(a, b):
    q, t = (a, b) if len(a) <= len(b) else (b, a)
    return 100 * edlib.align(q, t, mode='HW', task='distance')['editDistance'] / len(q)


def fmt(x):
    return f'{x:.1f}'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--runs', type=Path, required=True, help='runs_euk of euk_test.py')
    ap.add_argument('--wins', required=True, help='prefix of the locked test windows ({p}.full_its.fasta, ...)')
    ap.add_argument('--bench', type=Path, default=Path('../benchmarks/eukaryome'))
    ap.add_argument('--ref', type=Path, default=Path('../reference/culture_ref_v4'))
    ap.add_argument('--paper', type=Path, default=Path('.'))
    a = ap.parse_args()

    sc = a.runs / '06_scores'
    A2, A1 = rd(sc / 'A_primary_v2.copies.tsv'), rd(sc / 'A_primary_v1.copies.tsv')
    B2, B1 = ({r['accession']: r for r in rd(sc / f'B_primary_{v}.copies.tsv')} for v in ('v2', 'v1'))
    test = {r['asv']: r for r in rd(a.bench / 'overlap.asvs.tsv')}
    pred = {r['asv']: r for r in rd(a.bench / 'predictions.predictions.tsv')}
    T = {'ITS': 5.988026607538803, 'LSU': 3.0269792549075722, 'SSU': 0.806517311608961}  # predictions.lock

    def primary(rows_a, rows_b):
        return [rows_b.get(r['accession'], r) for r in rows_a if r['test_role'] in NOVEL]

    p2, p1 = primary(A2, B2), primary(A1, B1)
    fk = [r for r in p2 if is_known(r)]
    m = Macros()
    m.lines.append('% GENERATED by analysis/euk_followup.py: exploratory, written after the EUKARYOME results; do not edit.')

    # absent species in reference genera
    sp_rows = [r for r in p2 if r['test_role'] == NOVEL_SP]
    sp_fk = [r for r in sp_rows if is_known(r)]
    m.add('EkFxSpPct', pct(len(sp_fk), len(sp_rows)), 'absent species in reference genera')
    m.add('EkFxSpTaxa', num(len({r['organism'] for r in sp_fk})))
    m.add('EkFxSpTaxaAll', num(len({r['organism'] for r in sp_rows})))
    m.add('EkFxSpGenusScored', num(sum(r['organism'] not in ('Dentiscutata erythropus',) for r in sp_rows)))

    # distances to every reference culture, named or genus-only
    cul = {r['culture']: r for r in rd(a.ref / 'cultures.tsv')}
    mains = [r for r in rd(a.ref / 'copies.tsv') if r['status'] == 'retained' and r['copy_class'] == 'main']
    ref = {lab: read_fasta(a.ref / 'fasta' / f'{mk}.fasta') for mk, lab in MARKERS}
    win = {lab: read_fasta(f'{a.wins}.{mk}.fasta') for mk, lab in MARKERS}
    by_cul = defaultdict(lambda: defaultdict(set))
    for r in mains:
        for lab in ref:
            if r['accession'] in ref[lab]:
                by_cul[r['culture']][lab].add(ref[lab][r['accession']])
    rows = []
    for r in fk:
        x = r['accession']
        d = {}
        for c, segs in by_cul.items():
            d[c] = {lab: (min(dist(win[lab][x], s) for s in segs[lab]) if x in win[lab] and segs[lab] else None)
                    for lab in ref}
        inside = [c for c in d if all(d[c][lab] is not None and d[c][lab] <= T[lab] for lab in ref)]
        named_inside = [c for c in inside if cul[c]['named'] == 'True']
        rows.append({'acc': x, 'organism': r['organism'], 'assigned': ';'.join(called(r)), 'locked': bool(pred[x]['inside']),
                     'inside': inside, 'named_inside': named_inside,
                     'genus_only_inside': [c for c in inside if cul[c]['named'] != 'True'],
                     'near': {lab: min((v[lab], c) for c, v in d.items() if v[lab] is not None) for lab in ref}})
    outside = [r for r in rows if not r['locked']]
    go = [r for r in outside if r['genus_only_inside'] and not r['named_inside']]
    none = [r for r in outside if not r['inside']]
    m.add('EkFxOutside', num(len(outside)), 'false-known assignments outside the locked prediction')
    m.add('EkFxGenusOnlyInside', num(len(go)))
    m.add('EkFxGenusOnlyCultures', num(len({c for r in go for c in r['genus_only_inside']})))
    m.add('EkFxGenusOnlyTaxa', ' and '.join(sorted({f"\\spn{{{r['organism']}}}" for r in go})))
    its = [r['near']['ITS'][0] for r in go]
    ssu = [r['near']['SSU'][0] for r in go]
    m.add('EkFxGenusOnlyITS', f'{fmt(min(its))}--{fmt(max(its))}\\%' if its else '--')
    m.add('EkFxGenusOnlySSU', f'{fmt(min(ssu))}--{fmt(max(ssu))}\\%' if ssu else '--')
    m.add('EkFxNotInside', num(len(none)))
    m.add('EkFxNotInsideTaxa', ' and '.join(sorted({f"\\spn{{{r['organism']}}}" for r in none})) or '--')
    lsu_none = [r['near']['LSU'][0] for r in none]
    m.add('EkFxNotInsideLSU', f'{fmt(min(lsu_none))}--{fmt(max(lsu_none))}\\%' if lsu_none else '--')
    m.add('EkFxNotInsideAssigned', ' and '.join(sorted({f"\\spn{{{s}}}" for r in none for s in r['assigned'].split(';')})) or '--')

    # the ITS distance rule here
    fk1 = sum(map(is_known, p1))
    kn2 = [r for r in A2 if r['test_role'] == KNOWN]
    kn1 = [r for r in A1 if r['test_role'] == KNOWN]
    kept = lambda rows: sum(is_known(r) and r['organism'] in called(r) for r in rows)  # noqa: E731
    m.add('EkFxRulePrevented', num(fk1 - len(fk)), 'the ITS distance rule')
    m.add('EkFxRuleCost', num(kept(kn1) - kept(kn2)))

    # genus given to sequences of absent genera
    def lin(rows):
        return [r for r in rows if r['test_role'] == NOVEL_LIN and r['organism'].split()[0] not in NO_GENUS_OUTCOME_GENERA]
    lb, la = lin(p2), lin([r for r in A2 if r['test_role'] in NOVEL])
    gb = [r for r in lb if r['final_genus_call'] == '1']
    ga = [r for r in la if r['final_genus_call'] == '1']
    m.add('EkFxLinGivenPct', pct(len(gb), len(lb)), 'absent genera')
    m.add('EkFxLinGivenA', num(len(ga)))
    m.add('EkFxLinGivenAPct', pct(len(ga), len(la)))
    by_gen = Counter(r['organism'].split()[0] for r in gb)
    given = defaultdict(Counter)
    for r in gb:
        given[r['organism'].split()[0]][';'.join(sorted(set(filter(None, r['call_genera'].split(';')))))] += 1
    named = [(g, n) for g, n in by_gen.most_common() if '.' not in g][:2]
    m.add('EkFxLinGivenTop', ' and '.join(
        f"\\spn{{{g}}} ({n} sequences, given \\spn{{{given[g].most_common(1)[0][0].replace(';', '} or \\spn{')}}})"
        for g, n in named))
    m.add('EkFxLinGivenTopN', num(sum(n for _, n in named)))
    m.add('EkFxLinGivenGenera', num(len(by_gen)))

    # sequences of reference species: what the ITS rule changed, and the short-5.8S type
    dem = [r for r in kn2 if r['its_rule_fired'] == '1']
    m.add('EkFxRuleDemotedInsideOwn', num(sum(pred[r['accession']]['own_species_in_v4'] in pred[r['accession']]['inside'].split('; ')
                                             for r in dem)), 'reference species')
    dits = [float(r['its_nearest_training_pct']) for r in dem]
    m.add('EkFxRuleDemotedITS', f'{fmt(min(dits))}--{fmt(max(dits))}\\%' if dits else '--')
    kdiv = [r for r in kn2 if r['status'] == 'divergent class']
    m.add('EkFxKnownDivergent', num(len(kdiv)))
    m.add('EkFxKnownDivergentRhiz', num(sum(r['organism'].split()[0] in ('Rhizophagus', 'Rhizoglomus') for r in kdiv)))
    # sequences with the short-5.8S motif labelled Rhizoglomus (or Rhizophagus): how they were classified (condition A)
    mot = {r['accession']: r for r in rd(a.runs / 'report' / 'motif_reads.tsv')}
    rh = [r for r in mot.values() if r['organism'].split()[0] in ('Rhizophagus', 'Rhizoglomus')]
    m.add('EkFxMotifRhiz', num(len(rh)), 'short-5.8S motif, Rhizoglomus labels')
    m.add('EkFxMotifRhizDiv', num(sum(r['status'] == 'divergent class' for r in rh)))
    m.add('EkFxMotifRhizLineage', num(sum(r['status'] == 'novel lineage' for r in rh)))
    m.add('EkFxMotifRhizNewSp', num(sum(r['status'] == 'novel species, genus known' for r in rh)))

    (a.paper / 'numbers_euk_followup.tex').write_text('\n'.join(m.lines) + '\n')
    out = a.paper / 'analysis' / 'euk_followup'
    out.mkdir(exist_ok=True)
    with open(out / 'false_known_distances.tsv', 'w') as fh:
        fh.write('accession\torganism\tassigned\tin_locked_prediction\tinside_named\tinside_genus_only\t'
                 'nearest_ITS\tITS_pct\tnearest_LSU\tLSU_pct\tnearest_SSU\tSSU_pct\n')
        for r in rows:
            n = r['near']
            fh.write('\t'.join([r['acc'], r['organism'], r['assigned'], str(r['locked']), ';'.join(r['named_inside']),
                                ';'.join(r['genus_only_inside'])] +
                               [f"{n[lab][1]}\t{n[lab][0]:.2f}" for lab in ('ITS', 'LSU', 'SSU')]) + '\n')
    with open(out / 'absent_genera_given_genus.tsv', 'w') as fh:
        fh.write('label_genus\tsequences_given_a_genus_B\tgenus_given\n')
        for g, n in by_gen.most_common():
            fh.write(f"{g}\t{n}\t{'; '.join(f'{k} {v}' for k, v in given[g].most_common())}\n")
    print(f'numbers_euk_followup.tex: {sum(l.startswith(chr(92)) for l in m.lines)} macros; '
          f'{len(fk)} false known, {len(outside)} outside the prediction: {len(go)} inside a genus-only culture only, '
          f'{len(none)} inside no culture')
    for r in rows:
        n = r['near']
        print(f"  {r['acc']} {r['organism']:<26} -> {r['assigned']:<45} locked={r['locked']!s:<5} "
              f"genus-only inside={';'.join(c.split(' | ')[1] for c in r['genus_only_inside'])} "
              + ' '.join(f"{lab} {n[lab][0]:.2f} ({n[lab][1].split(' | ')[0]})" for lab in ('ITS', 'LSU', 'SSU')))


if __name__ == '__main__':
    main()
